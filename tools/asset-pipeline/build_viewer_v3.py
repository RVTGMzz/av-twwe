"""Bundle Trainer V3 metadata for the offline Asset Viewer (tools/asset-pipeline/viewer_v3/).

Usage (repo root): python tools/asset-pipeline/build_viewer_v3.py
Re-run after any change to the layer/idle/walk atlases. Writes viewer_v3/data.js (committed, so the viewer
opens from file:// right after cloning).
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
META = os.path.join(ROOT, 'assets', 'characters', 'trainer', 'metadata')


def load(name):
    with open(os.path.join(META, name + '.json'), encoding='utf-8') as fh:
        return json.load(fh)


def main():
    layers, idle, walk = load('trainer_v3_layers'), load('trainer_v3_anim_idle'), load('trainer_v3_anim_walk')
    anims = {}
    # still = layers_v3 atlases: one row, 8 direction columns
    still = {}
    for v in layers['variants']:
        g = v['presets'][0]
        full = v['id'].endswith('_full')
        slot = v['slot']
        still.setdefault(g, {}).setdefault(slot, {})['full' if full else 'visible'] = v['file']
    anims['still'] = {'frames': 1, 'durations': [1000], 'layout': 'columns=directions', 'files': still}
    for name, meta in (('idle', idle), ('walk', walk)):
        files = {}
        for v in meta['variants']:
            g = v['presets'][0]
            files.setdefault(g, {}).setdefault(v['slot'], {})['full' if v.get('full') else 'visible'] = v['file']
        anims[name] = {'frames': meta['frame_count'], 'durations': meta['durations_ms'], 'layout': 'rows=directions,columns=frames', 'files': files}
    data = {
        'canvas': layers['canvas'], 'pivot': layers['pivot'], 'directions': layers['directions'],
        'slots': layers['slots'], 'render_order': layers['render_order'], 'animations': anims,
        'status': {'layers': layers['status'], 'idle': idle['status'], 'walk': walk['status']},
        'notes': ['Walk has no covered-area (full) layers yet: hiding a garment while walking shows gaps.',
                  'One skin tone and one outfit per gender in V3 so far.'],
    }
    out = os.path.join(ROOT, 'tools', 'asset-pipeline', 'viewer_v3', 'data.js')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', encoding='utf-8') as fh:
        fh.write('// GENERATED by tools/asset-pipeline/build_viewer_v3.py, do not edit.\nwindow.AEVORIA_V3 = ' + json.dumps(data) + ';\n')
    print('wrote', os.path.relpath(out, ROOT))


if __name__ == '__main__':
    main()
